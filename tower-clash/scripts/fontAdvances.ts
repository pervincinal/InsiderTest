/**
 * ART-17: writes tests/render/fontAdvances.ts — per-glyph advance widths (1 px font size) of the
 * game's two canvas stacks (Fredoka first; Nunito first while the UI is Russian) at weights 500 and
 * 700, measured by headless Chromium with the bundled public/fonts faces. The render fit tests
 * (tests/render/contrast.test.ts) sum them to lay out translated numeral lines the way the game
 * measures them, without a browser. Only the glyphs of the challenge card / shop lines the tests
 * lay out (in every locale) plus digits and number punctuation are kept.
 *
 *   npx tsx scripts/fontAdvances.ts
 *
 * Uses the preinstalled sandbox Chromium when /opt/pw-browsers exists (never runs `playwright
 * install`). The page and the fonts are served by request routing, no server needed.
 */
import { chromium } from '@playwright/test';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { en } from '../src/ui/locales/en';
import { az } from '../src/ui/locales/az';
import { ru } from '../src/ui/locales/ru';
import { tr } from '../src/ui/locales/tr';
import { FONT, FONT_RU } from '../src/render/widgets';

const ROOT = resolve(import.meta.dirname, '..');
const SANDBOX_CHROMIUM = '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell';
const OUT = resolve(ROOT, 'tests/render/fontAdvances.ts');

/** Keys whose texts the fit tests lay out. */
const KEYS = [
  'daily.newIn',
  'daily.newInTime',
  'weekly.newIn',
  'weekly.newInDays',
  'daily.reward',
  'weekly.reward',
  'daily.locked',
  'weekly.locked',
  'shop.tier',
  'daily.streak',
  'daily.streakNext',
  'weekly.streak',
] as const;

async function main(): Promise<void> {
  const dicts: readonly Readonly<Record<string, string>>[] = [en, az, ru, tr];
  const texts: string[] = dicts.flatMap((d) => KEYS.map((k) => d[k] ?? ''));
  const chars = [...new Set([...texts.join(''), ...("0123456789+−-.,:/% ★()·'" as string)])]
    .filter((c) => c !== '{' && c !== '}' && c !== '|')
    .sort()
    .join('');
  const faces: string[] = [...(readFileSync(resolve(ROOT, 'index.html'), 'utf8').match(/@font-face \{[\s\S]*?\}/g) ?? [])];
  // the Latin Nunito face is registered at runtime while the UI is Russian (src/render/fonts.ts)
  faces.push("@font-face { font-family: 'Nunito'; font-style: normal; font-weight: 500 700; font-display: block; src: url('./fonts/nunito-latin.woff2') format('woff2'); }");
  const browser = await chromium.launch({ executablePath: existsSync(SANDBOX_CHROMIUM) ? SANDBOX_CHROMIUM : undefined });
  try {
    const page = await browser.newPage();
    await page.route('http://fonts.test/**', (route) => {
      const path = new URL(route.request().url()).pathname;
      if (path.startsWith('/fonts/')) return route.fulfill({ body: readFileSync(resolve(ROOT, 'public', path.slice(1))), contentType: 'font/woff2' });
      return route.fulfill({ body: `<!doctype html><html><head><style>${faces.join('\n')}</style></head><body><canvas></canvas></body></html>`, contentType: 'text/html' });
    });
    await page.goto('http://fonts.test/');
    const result = await page.evaluate(
      async ({ chars, stacks, texts }) => {
        for (const w of [500, 700]) for (const f of ['Fredoka', 'Nunito']) await document.fonts.load(`${w} 100px ${f}`, chars);
        const ctx = document.querySelector('canvas')!.getContext('2d')!;
        const tables: Record<string, number[]> = {};
        for (const [name, family] of Object.entries(stacks))
          for (const w of [500, 700]) {
            ctx.font = `${w} 100px ${family}`;
            tables[`${name}${w}`] = [...chars].map((c) => Math.round(ctx.measureText(c).width * 100) / 10000);
          }
        // how far a sum of advances (no kerning) is from the measured text, over the sampled texts
        let err = 0;
        for (const [name, family] of Object.entries(stacks))
          for (const w of [500, 700]) {
            ctx.font = `${w} 100px ${family}`;
            const adv = tables[`${name}${w}`]!;
            for (const s of texts) {
              const real = ctx.measureText(s).width / 100;
              const sum = [...s].reduce((a, c) => a + (adv[chars.indexOf(c)] ?? 0), 0);
              err = Math.max(err, Math.abs(sum - real) / real);
            }
          }
        return { tables, err };
      },
      { chars, stacks: { latin: FONT, ru: FONT_RU }, texts: texts.map((s) => s.replace(/\{[^}]*\}/g, '12')) },
    );
    const rows = Object.entries(result.tables).map(([k, v]) => `  ${k}: [${v.join(', ')}],`);
    writeFileSync(
      OUT,
      [
        '/* Generated by scripts/fontAdvances.ts (ART-17) from public/fonts in headless Chromium — do not edit by hand. */',
        '',
        '/** Glyphs of the tables below, in order. */',
        `export const ADVANCE_CHARS = ${JSON.stringify(chars)};`,
        '',
        "/** Advance width per glyph at 1 px: `latin` = the Fredoka-first stack (FONT), `ru` = the Nunito-first stack (FONT_RU). */",
        'export const ADVANCES: Readonly<Record<"latin500" | "latin700" | "ru500" | "ru700", readonly number[]>> = {',
        ...rows,
        '};',
        '',
        '/** Largest relative gap between a summed line (no kerning) and Chromium\'s measureText over the sampled texts. */',
        `export const ADVANCE_ERROR = ${result.err.toFixed(4)};`,
        '',
      ].join('\n'),
    );
    console.log(`wrote ${OUT}: ${chars.length} glyphs × 4 faces, max summed-vs-measured error ${(result.err * 100).toFixed(2)} %`);
  } finally {
    await browser.close();
  }
}

main().catch((err: unknown) => {
  console.error(err);
  process.exit(1);
});
